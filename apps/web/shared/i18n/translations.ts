const RUB_PRICE_PATTERN = /(\d[\d\s\u00a0\u202f]*(?:[.,]\d+)?)\s*₽/g;

function convertRublesToDollars(value: string) {
  return value.replace(RUB_PRICE_PATTERN, (_, amount: string) => {
    const rubles = Number(amount.replace(/[\s\u00a0\u202f]/g, '').replace(',', '.'));

    if (!Number.isFinite(rubles)) return `${amount} RUB`;

    return new Intl.NumberFormat('en-US', {
      style: 'currency',
      currency: 'USD',
      maximumFractionDigits: 0,
    }).format(rubles / RUB_PER_USD);
  });
}

export function translateRussianText(value: string) {
  const englishAudienceValue = value.replace(
    '+7 999 000-00-00',
    '+1 555 000-0000',
  );

  if (!/[А-Яа-яЁё₽]/.test(englishAudienceValue)) {
    return englishAudienceValue;
  }

  let translated = convertRublesToDollars(englishAudienceValue);
  translated = translated.replaceAll('₽', '$');

  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    translated = translated.replace(pattern, replacement);
  }

  for (const [russian, english] of SORTED_PHRASES) {
    translated = translated.replaceAll(russian, english);
  }

  translated = translated
    .replace(/(^|\s)до(?=\s|$)/gi, '$1up to')
    .replace(/(?<![А-Яа-яЁё])м²(?![А-Яа-яЁё])/g, 'm²')
    .replace(/(?<![А-Яа-яЁё])см(?![А-Яа-яЁё])/g, 'cm')
    .replace(/(?<![А-Яа-яЁё])м(?![А-Яа-яЁё])/g, 'm')
    .replace(/(?<![А-Яа-яЁё])шт\.?(?![А-Яа-яЁё])/g, 'pcs');

  return translated;
}

